export function detectLanguage(languages = []) {
  return languages[0]?.toLowerCase().split('-')[0] === 'pl' ? 'pl' : 'en';
}

export function translate(language, key, variables = {}) {
  const value = messages[language]?.[key] ?? messages.en[key];
  if (typeof value !== 'string') throw new Error('Missing translation: ' + key);
  return value.replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? '{' + name + '}'));
}
